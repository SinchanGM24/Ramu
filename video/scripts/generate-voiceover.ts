import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { EdgeTTS } from "node-edge-tts";
import { narration } from "../src/data/workflow-script";

const audioDirectory = join(
  dirname(fileURLToPath(import.meta.url)),
  "../public/audio",
);
const voiceTimelinePath = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/data/voice-timing.generated.ts",
);
const voice = process.env.RAMU_VIDEO_TTS_VOICE || "id-ID-GadisNeural";
const rate = process.env.RAMU_VIDEO_TTS_RATE || "-10%";

function timestamp(seconds: number) {
  const totalMilliseconds = Math.round(seconds * 1000);
  const hours = Math.floor(totalMilliseconds / 3_600_000);
  const minutes = Math.floor((totalMilliseconds % 3_600_000) / 60_000);
  const remainder = totalMilliseconds % 60_000;
  const wholeSeconds = Math.floor(remainder / 1000);
  const milliseconds = remainder % 1000;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}:${String(wholeSeconds).padStart(2, "0")},${String(milliseconds).padStart(3, "0")}`;
}

type VoiceWord = { part: string; start: number; end: number };

function captionTimeline(words: VoiceWord[]) {
  const expectedWords = narration.flatMap((cue) =>
    cue.text.trim().split(/\s+/),
  );
  if (words.length !== expectedWords.length)
    throw new Error(
      `Metadata kata tidak cocok: ${words.length} diterima, ${expectedWords.length} diharapkan.`,
    );
  const captions: Array<{ start: number; end: number; text: string }> = [];
  for (let index = 0; index < words.length; index += 7) {
    const group = words.slice(index, index + 7);
    captions.push({
      start: group[0].start / 1000,
      end: group.at(-1)!.end / 1000,
      text: group.map((word) => word.part.trim()).join(" "),
    });
  }
  return captions;
}

async function main() {
  await mkdir(audioDirectory, { recursive: true });
  const tts = new EdgeTTS({
    lang: "id-ID",
    rate,
    saveSubtitles: true,
    voice,
  });
  await tts.ttsPromise(
    narration.map((cue) => cue.text).join(" "),
    join(audioDirectory, "voice-full.mp3"),
  );
  const words = JSON.parse(
    await readFile(join(audioDirectory, "voice-full.mp3.json"), "utf8"),
  ) as VoiceWord[];
  const captions = captionTimeline(words);
  const srt = captions
    .map(
      (caption, index) =>
        `${index + 1}\n${timestamp(caption.start)} --> ${timestamp(caption.end)}\n${caption.text}`,
    )
    .join("\n\n");
  await writeFile(
    join(audioDirectory, "ramu-workflow.srt"),
    `${srt}\n`,
    "utf8",
  );
  await writeFile(
    voiceTimelinePath,
    `// Generated by scripts/generate-voiceover.ts from Edge TTS word timings.\nexport const voiceTimeline = ${JSON.stringify(captions, null, 2)} as const;\n`,
    "utf8",
  );
  console.log("Dibuat: voice-full.mp3 dan ramu-workflow.srt");
}

void main();
